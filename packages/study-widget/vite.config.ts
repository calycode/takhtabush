import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import preact from '@preact/preset-vite';
import tailwindcss from '@tailwindcss/vite';
import { defineConfig, type Plugin } from 'vite';

// Vite/Preact aliases must be absolute (see the webapp config for the rationale).
const preactEntry = (specifier: string) => fileURLToPath(import.meta.resolve(specifier));

const outDir = fileURLToPath(new URL('./dist', import.meta.url));
const compiledFile = fileURLToPath(new URL('./compiled/v1.html.ts', import.meta.url));

/**
 * Produce a single self-contained HTML resource (`ui://…#v1.html`) and a TS module
 * that the Worker serves directly — no separate asset requests, and no cross-package
 * build wiring (SPEC §9.8).
 */
function inlineSingleFile(): Plugin {
   return {
      name: 'mcp-apps-inline',
      closeBundle() {
         const htmlPath = resolve(outDir, 'index.html');
         if (!existsSync(htmlPath)) return;

         let html = readFileSync(htmlPath, 'utf8');
         html = html.replace(
            /<script[^>]*\ssrc="\.\/([^"]+)"[^>]*><\/script>/g,
            (_match, src: string) =>
               `<script type="module">\n${readFileSync(resolve(outDir, src), 'utf8')}\n</script>`,
         );
         html = html.replace(
            /<link[^>]*rel="stylesheet"[^>]*href="\.\/([^"]+)"[^>]*\/?>/g,
            (_match, href: string) =>
               `<style>\n${readFileSync(resolve(outDir, href), 'utf8')}\n</style>`,
         );

         writeFileSync(resolve(outDir, 'v1.html'), html);
         writeFileSync(
            compiledFile,
            '/* AUTO-GENERATED by @caly/study-widget build. Do not edit. */\n' +
               `export const STUDY_WIDGET_HTML = ${JSON.stringify(html)};\n`,
         );
      },
   };
}

export default defineConfig({
   plugins: [preact({ reactAliasesEnabled: false }), tailwindcss(), inlineSingleFile()],
   base: './',
   build: {
      outDir: 'dist',
      emptyOutDir: true,
   },
   define: {
      'process.env.IS_PREACT': JSON.stringify('true'),
   },
   resolve: {
      alias: [
         { find: /^react$/, replacement: preactEntry('preact/compat') },
         { find: /^react-dom$/, replacement: preactEntry('preact/compat') },
         { find: /^react-dom\/client$/, replacement: preactEntry('preact/compat/client') },
         { find: /^react\/jsx-runtime$/, replacement: preactEntry('preact/jsx-runtime') },
         { find: /^react\/jsx-dev-runtime$/, replacement: preactEntry('preact/jsx-dev-runtime') },
      ],
   },
});
